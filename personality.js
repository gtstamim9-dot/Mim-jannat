const EMOJI_RE = /\p{Extended_Pictographic}/u;
const SERIOUS_RE = /(error|failed|exception|ত্রুটি|ব্যর্থ|সতর্ক|warning|জরুরি)/i;
const POOLS = {
  islamic: ['🤍', '🌙', '✨'],
  shy: ['🥺', '🌸', '💗'],
  general: ['✨', '🌷', '🤍', '🫧', '🦋']
};
let rot = 0;
// Guarantees a relevant emoji in normal replies (the model sometimes forgets), but never in serious/technical replies.
function ensureEmoji(text, userText = '') {
  const answer = String(text || '').trim();
  if (!answer || EMOJI_RE.test(answer) || SERIOUS_RE.test(answer)) return answer;
  const ctx = `${userText} ${answer}`;
  const pool = /(আল্লাহ|ইনশাআল্লাহ|আলহামদুলিল্লাহ|মাশাআল্লাহ|সালাম|সুবহানাল্লাহ|জাযাকাল্লাহ|দোয়া|নামাজ|ইসলাম)/.test(ctx) ? POOLS.islamic
    : /(দুঃখিত|ধন্যবাদ|স্বাগতম|হিহি|লজ্জা)/.test(ctx) ? POOLS.shy : POOLS.general;
  rot = (rot + 1) % pool.length;
  return `${answer} ${pool[rot]}`;
}

